// Rasterizes Natural Earth land (via world-atlas) into an equirectangular
// bitmask and writes it as a base64 ES module consumed by src/land.js.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const W = 1440;
const H = 720;

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const rings = [];
for (const f of land.features ?? [land]) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) rings.push(unwrap(ring));
}

// Make longitudes continuous across the antimeridian. Rings that circle a
// pole (Antarctica) end up 360° apart, so close them over that pole.
function unwrap(ring) {
  const out = [ring[0].slice()];
  for (let i = 1; i < ring.length; i++) {
    let lon = ring[i][0];
    const prev = out[i - 1][0];
    while (lon - prev > 180) lon -= 360;
    while (lon - prev < -180) lon += 360;
    out.push([lon, ring[i][1]]);
  }
  const first = out[0];
  const last = out[out.length - 1];
  if (Math.abs(last[0] - first[0]) > 180) {
    const pole = out.reduce((s, p) => s + p[1], 0) < 0 ? -90 : 90;
    out.push([last[0], pole], [first[0], pole]);
  }
  return out;
}

const bits = new Uint8Array((W * H) / 8);
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5) * (180 / H);
  for (const ring of rings) {
    const xs = [];
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[j];
      const [x2, y2] = ring[i];
      if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
    xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const x0 = Math.ceil(((xs[k] + 180) / 360) * W - 0.5);
    const x1 = Math.floor(((xs[k + 1] + 180) / 360) * W - 0.5);
    for (let x = x0; x <= x1; x++) {
      const idx = y * W + (((x % W) + W) % W);
      bits[idx >> 3] ^= 1 << (idx & 7);
    }
  }
  }
}

const b64 = Buffer.from(bits).toString("base64");
writeFileSync(
  new URL("../src/land-data.js", import.meta.url),
  `// Generated by scripts/build-land.mjs — do not edit.\n// Equirectangular land bitmask, ${W}x${H}, LSB-first, row 0 = 90°N, col 0 = 180°W.\nexport const LAND_W = ${W};\nexport const LAND_H = ${H};\nexport const LAND_B64 = "${b64}";\n`,
);

if (process.argv.includes("--preview")) {
  for (let y = 0; y < H; y += 16) {
    let s = "";
    for (let x = 0; x < W; x += 8) {
      const idx = y * W + x;
      s += bits[idx >> 3] & (1 << (idx & 7)) ? "#" : ".";
    }
    console.log(s);
  }
}
