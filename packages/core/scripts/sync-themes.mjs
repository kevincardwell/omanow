// Pulls the stock Omarchy themes' colors.toml from omacom/omarchy (MIT) and
// writes them as src/themes.js, keeping only the keys the globe uses.
import { writeFileSync } from "node:fs";
import { parseColorsToml, THEME_KEYS } from "../src/theme.js";

const REPO = "omacom/omarchy";
// Some themes leave out a key; borrow the closest one they do set.
const FALLBACK = { orange: "yellow", bright_yellow: "yellow", bright_cyan: "cyan", bright_magenta: "magenta", selection: "lighter_background", muted: "dark_foreground" };
const list = await fetch(`https://api.github.com/repos/${REPO}/contents/themes`).then((r) => {
  if (!r.ok) throw new Error(`theme list: HTTP ${r.status}`);
  return r.json();
});

const themes = {};
for (const { name, type } of list) {
  if (type !== "dir") continue;
  const res = await fetch(`https://raw.githubusercontent.com/${REPO}/HEAD/themes/${name}/colors.toml`);
  if (!res.ok) continue;
  const colors = parseColorsToml(await res.text());
  for (const [key, from] of Object.entries(FALLBACK)) colors[key] ??= colors[from];
  if (!THEME_KEYS.every((k) => colors[k])) continue;
  themes[name] = Object.fromEntries(THEME_KEYS.map((k) => [k, colors[k]]));
}

writeFileSync(
  new URL("../src/themes.js", import.meta.url),
  `// Generated by scripts/sync-themes.mjs from ${REPO} (MIT). Do not edit.\nexport const THEMES = ${JSON.stringify(themes, null, 2)};\n`,
);
console.log(`themes.js: ${Object.keys(themes).length} themes`);
