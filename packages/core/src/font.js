export const MICRO_H = 5;

export function foldLabel(text) {
  return text.normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase().replace(/[^A-Z0-9 .'-]/g, "");
}

export function microWidth(text) {
  return text.length ? text.length * 4 - 1 : 0;
}

export function drawMicro(text, x, y, plot) {
  for (let i = 0; i < text.length; i++) {
    const g = MICRO[text[i]];
    if (!g) continue;
    for (let row = 0; row < MICRO_H; row++) {
      for (let col = 0; col < 3; col++) if (g[row][col] === "#") plot(x + i * 4 + col, y + row);
    }
  }
}
